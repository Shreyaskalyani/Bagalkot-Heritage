export function detectLanguageFromText(text, defaultLang = 'en') {
  if (/[\u0C80-\u0CFF]/.test(text)) return 'kn';
  if (/[\u0900-\u097F]/.test(text)) return 'hi';
  return defaultLang;
}

function escapeRegex(str) {
  return str.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function matchesKeyword(text, keyword) {
  const normKw = keyword.toLowerCase().trim();
  if (!normKw) return false;

  // Single latin alphanumeric word -> enforce word boundary so 'dam' won't match 'badami'
  if (/^[a-z0-9]+$/i.test(normKw)) {
    const rx = new RegExp(`(\\b|^)${escapeRegex(normKw)}(\\b|$)`, 'i');
    return rx.test(text);
  }

  // Phrases or longer strings -> regular substring inclusion
  if (normKw.includes(' ') || normKw.length >= 4) {
    return text.includes(normKw);
  }

  // Short non-latin word: check if query contains it as an independent token
  const words = text.split(/[\s,?.!;:—–"'/()[\]{}]+/);
  return words.some((w) => w === normKw || (w.length <= 5 && w.startsWith(normKw)));
}

